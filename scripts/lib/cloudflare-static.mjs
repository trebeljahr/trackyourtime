/**
 * The hosted web app is an assets-only Cloudflare Worker (wrangler.jsonc): no
 * script runs, so what packages/client/serve.mjs does per request has to be
 * written into the upload as files Cloudflare reads.
 *
 * - `_redirects`: the legacy root addresses (`/track` → `/app/track/`).
 * - `_headers`: no framing, no sniffing, and no-cache on the two JSON files a
 *   deploy is judged by.
 *
 * Both are rendered from packages/client/static-site-rules.mjs, the list
 * serve.mjs uses, so the two hosts cannot drift. No Cache-Control on hashed
 * assets: Cloudflare applies `_headers` to a 404 too, so marking
 * `/_next/static/*` immutable would let a browser keep a missing chunk's 404
 * for a year. Cloudflare's default (`max-age=0, must-revalidate` with an
 * ETag) costs a free revalidation instead.
 *
 * `checkLimits` refuses an upload Workers Free would reject, or cut short.
 * docs/deploy.md → Web app on Cloudflare.
 */
import { readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

import { LEGACY_APP_SEGMENTS, NO_FRAMING, NO_SNIFFING } from "../../packages/client/static-site-rules.mjs";

/** Workers Free, per Worker version. https://developers.cloudflare.com/workers/platform/limits/ */
export const LIMITS = Object.freeze({
  files: 20_000,
  fileBytes: 25 * 1024 * 1024,
  headerRules: 100,
  staticRedirects: 2_000,
  dynamicRedirects: 100,
});

/** Files whose answer must never be a cached one: CI and open tabs read them to learn what is live. */
export const NO_CACHE_PATHS = Object.freeze(["/version.json", "/release-assets.json"]);

const GENERATED = "# Generated by scripts/cloudflare-static.mjs from packages/client/static-site-rules.mjs.";

/** Header names as Cloudflare prints them; the rules module keeps them lower-case for node:http. */
const titleCase = (name) => name.replace(/(^|-)([a-z])/g, (_, dash, letter) => dash + letter.toUpperCase());

/**
 * `_redirects`. Two lines per old segment: the bare address and everything
 * under it. Straight to the trailing-slash form, which is where the static
 * host would send `/app/track` next anyway. Cloudflare keeps the query string.
 */
export const renderRedirects = (segments = LEGACY_APP_SEGMENTS) =>
  [
    GENERATED,
    ...segments.flatMap((segment) => [`/${segment} /app/${segment}/ 308`, `/${segment}/* /app/${segment}/:splat 308`]),
    "",
  ].join("\n");

/** `_headers`. */
export const renderHeaders = () =>
  [
    GENERATED,
    "/*",
    ...Object.entries({ ...NO_SNIFFING, ...NO_FRAMING }).map(([name, value]) => `  ${titleCase(name)}: ${value}`),
    ...NO_CACHE_PATHS.flatMap((path) => ["", path, "  Cache-Control: no-cache"]),
    "",
  ].join("\n");

const listFiles = (root) => {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else found.push({ path: relative(root, path).split(sep).join("/"), size: statSync(path).size });
    }
  };
  walk(root);
  return found;
};

/** The rule lines of a `_headers` or `_redirects` text: everything but blanks, comments and header lines. */
const ruleLines = (text) => text.split("\n").filter((line) => line.trim() !== "" && !line.startsWith("#") && !/^\s/.test(line));

/**
 * Problems that would make Cloudflare refuse the upload or drop rules from it.
 * Empty means the directory fits Workers Free.
 *
 * @param {string} outDir
 * @param {{ headers?: string, redirects?: string }} [rendered]  the `_headers` / `_redirects` text, when written
 */
export const checkLimits = (outDir, rendered = {}) => {
  const problems = [];
  const files = listFiles(outDir);
  if (files.length > LIMITS.files) problems.push(`${files.length} files, above the ${LIMITS.files} a Worker version may hold`);
  for (const file of files) {
    if (file.size > LIMITS.fileBytes) problems.push(`${file.path} is ${file.size} bytes, above the ${LIMITS.fileBytes}-byte limit per file`);
  }
  if (rendered.headers !== undefined) {
    const rules = ruleLines(rendered.headers).length;
    if (rules > LIMITS.headerRules) problems.push(`_headers has ${rules} rules, above ${LIMITS.headerRules}`);
  }
  if (rendered.redirects !== undefined) {
    const rules = ruleLines(rendered.redirects);
    const dynamic = rules.filter((line) => line.split(/\s+/)[0].includes("*") || line.split(/\s+/)[0].includes(":")).length;
    if (dynamic > LIMITS.dynamicRedirects) problems.push(`_redirects has ${dynamic} dynamic rules, above ${LIMITS.dynamicRedirects}`);
    if (rules.length - dynamic > LIMITS.staticRedirects) {
      problems.push(`_redirects has ${rules.length - dynamic} static rules, above ${LIMITS.staticRedirects}`);
    }
  }
  return { problems, files: files.length, bytes: files.reduce((sum, file) => sum + file.size, 0) };
};
