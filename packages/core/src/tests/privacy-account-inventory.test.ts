import assert from "node:assert/strict";
import { it } from "node:test";
import { createKeyPair, createSigningPair, randomSecret, signPrivateChange } from "../privacy/crypto.js";
import { privateMemberKeyFingerprint, signPrivateWorkspaceDirectory, verifyPrivateWorkspaceDirectory } from "../privacy/directory.js";
import { signPrivateInitialProjectionRoot, verifyPrivateInitialProjection } from "../privacy/projection-snapshot.js";
import { signPrivateWorkspacePolicy } from "../privacy/mode-policy.js";
import { accountWorkspacePolicy, createPrivateAccountInventoryStore, PrivateAccountInventoryMissingError, signPrivateAccountInventory, type PrivateAccountWorkspace, type VerifiedPrivateAccountInventory } from "../privacy/account-inventory.js";
import { privateRecordDigest } from "../privacy/workspace-edits.js";
import { PrivateStorageIntegrityError, PrivateStorageLockedError } from "../privacy/storage.js";
import { memoryStorage } from "../storage.js";
import { createPrivateAccountInventorySync } from "../privacy/inventory-sync.js";
const scope = { server: "https://api.example.test", userId: "owner" };
async function fixture() {
  const signing = await createSigningPair(), encryption = await createKeyPair(), key = randomSecret(), state = { open: true }, current = () => state.open;
  const member = { userId: scope.userId, role: "owner" as const, canViewOthersTime: true, canViewOthersMoney: true, publicKey: encryption.publicKey, signingPublicKey: signing.publicKey };
  const signedDirectory = await signPrivateWorkspaceDirectory({ v: 1, server: scope.server, workspaceId: "private", ownerId: scope.userId, revision: 1, previousDigest: null, members: [member] }, signing.privateKey, null, new Map([[scope.userId, await privateMemberKeyFingerprint(scope.server, member)]]));
  const directory = await verifyPrivateWorkspaceDirectory(signedDirectory, { ...scope, workspaceId: "private" }, { ownerId: scope.userId, signingPublicKey: signing.publicKey, revision: 0, digest: null });
  const secrets = { privateKey: encryption.privateKey, signingPrivateKey: signing.privateKey };
  const root = await signPrivateInitialProjectionRoot({ directory, secrets, userId: scope.userId, migrationId: crypto.randomUUID(), sharedRecords: [], ownerPersonalRecords: [], personalDigests: new Map([[scope.userId, await privateRecordDigest([])]]), current });
  const snapshot = await verifyPrivateInitialProjection({ signed: root, sharedRecords: [], personalRecords: [], scope: { ...scope, workspaceId: "private" }, directory, secrets, current });
  const signedPolicy = await signPrivateWorkspacePolicy({ reportRangeTimeZone: "UTC", snapshot, directory, secrets, current });
  const workspaces: PrivateAccountWorkspace[] = [{ workspaceId: "standard", mode: "standard" }, { workspaceId: "private", mode: "encrypted", signedPolicy }];
  const writes = new Map<string, string>(), backing = memoryStorage();
  const storage = { ...backing, setItem: async (name: string, value: string) => { writes.set(name, value); await backing.setItem(name, value); } };
  const options = { ...scope, storage, signingPublicKey: signing.publicKey, exclusive: <T>(work: () => Promise<T>) => work(), resolveStorageKey: () => state.open ? { key, current } : null, capture: () => () => { if (!current()) throw new PrivateStorageLockedError(); } };
  const sign = (rows = workspaces, previous: VerifiedPrivateAccountInventory | null = null) => signPrivateAccountInventory({ ...scope, workspaces: rows, previous, signingPrivateKey: signing.privateKey, current });
  return { signing, state, options, writes, sign, workspaces };
}
it("requires explicit fresh local enrollment and chooses mode only from a complete authenticated inventory", async () => {
  const f = await fixture(), store = await createPrivateAccountInventoryStore(f.options), signed = await f.sign();
  await assert.rejects(store.read(), PrivateAccountInventoryMissingError);
  await assert.rejects(store.accept(signed), PrivateAccountInventoryMissingError);
  await assert.rejects(store.enroll(JSON.parse(JSON.stringify(signed))), PrivateAccountInventoryMissingError);
  const profile = await store.enroll(signed);
  assert.equal(profile.checkpoint.revision, 1);
  assert.equal(accountWorkspacePolicy(profile, scope, "standard").mode, "standard");
  assert.equal(accountWorkspacePolicy(profile, scope, "private").mode, "encrypted");
  assert.throws(() => accountWorkspacePolicy(profile, scope, "unknown"), /absent from the trusted/);
  assert.throws(() => accountWorkspacePolicy({ ...profile }, scope, "standard"), /current verified/);
  assert.ok(Object.isFrozen(profile.signed.inventory.workspaces));
  for (const raw of f.writes.values()) assert.doesNotMatch(raw, /account-workspace-inventory|signedPolicy|activationRoot|"mode"/);
});
it("cannot use standard workspace creation to add plaintext routing to a private account", async () => {
  const f = await fixture(), master = f.options.resolveStorageKey()!.key;
  const sync = await createPrivateAccountInventorySync({ ...f.options, resolveIdentity: () => ({ master, signingPrivateKey: f.signing.privateKey, signingPublicKey: f.signing.publicKey, current: () => f.state.open }) });
  await sync.enroll(await f.sign()); const before = await sync.exportRecovery();
  await assert.rejects(sync.prepareStandardWorkspace(), /encrypted initialization/); assert.deepEqual(await sync.exportRecovery(), before);
});
it("refuses private workspace removal/downgrade/replacement and accepts only consecutive account updates", async () => {
  const f = await fixture(), store = await createPrivateAccountInventoryStore(f.options), first = await f.sign(), profile = await store.enroll(first);
  await assert.rejects(f.sign([{ workspaceId: "standard", mode: "standard" }], profile), /cannot be removed/);
  await assert.rejects(f.sign([{ workspaceId: "private", mode: "standard" }], profile), /cannot be removed/);
  const changed = structuredClone(f.workspaces);
  const privateRow = changed.find((row) => row.mode === "encrypted")!;
  if (privateRow.mode === "encrypted") privateRow.signedPolicy.policy.activationRoot = "A".repeat(43);
  await assert.rejects(f.sign(changed, profile), /cannot be removed/);
  const second = await f.sign([...f.workspaces, { workspaceId: "new-standard", mode: "standard" }], profile);
  const next = await store.accept(second); assert.equal(next.checkpoint.revision, 2);
  await assert.rejects(store.accept(first), /rolled back/);
  const third = await f.sign(f.workspaces, next);
  const other = await createPrivateAccountInventoryStore({ ...f.options, storage: memoryStorage() });
  await other.restore(third, { revision: 3, digest: await privateRecordDigest(third.inventory) });
  const fourth = await f.sign(f.workspaces, await other.read());
  await assert.rejects(store.accept(fourth), /skipped a revision/);
  assert.equal((await store.read()).checkpoint.revision, 2);
});
it("restores a new device only against an independently trusted exact checkpoint and preserves newer local state", async () => {
  const f = await fixture(), firstStore = await createPrivateAccountInventoryStore(f.options), first = await f.sign();
  const old = await firstStore.enroll(first), second = await f.sign(f.workspaces, old), current = await firstStore.accept(second);
  const device = await createPrivateAccountInventoryStore({ ...f.options, storage: memoryStorage() });
  await assert.rejects(device.restore(first, current.checkpoint), /trusted recovery checkpoint/);
  await assert.rejects(device.restore(second, { ...current.checkpoint, digest: "A".repeat(43) }), /trusted recovery checkpoint/);
  const restored = await device.restore(second, current.checkpoint);
  assert.equal(restored.checkpoint.digest, current.checkpoint.digest);
  await assert.rejects(device.restore(first, old.checkpoint), /cannot be replaced/);
  await assert.rejects(device.restore(second, old.checkpoint), /trusted recovery checkpoint/);
  assert.equal((await device.read()).checkpoint.revision, 2);
});
it("refuses forged signatures, wrong account/server, corrupt storage and locked state without defaulting to standard", async () => {
  const f = await fixture(), store = await createPrivateAccountInventoryStore(f.options), signed = await f.sign(), profile = await store.enroll(signed);
  const forged = structuredClone(signed); forged.signature = await signPrivateChange((await createSigningPair()).privateKey, forged.inventory);
  await assert.rejects(store.accept(forged), /signature/);
  const changed = await createPrivateAccountInventoryStore({ ...f.options, signingPublicKey: (await createSigningPair()).publicKey });
  await assert.rejects(changed.read(), /key or initial revision/);
  const wrongScope = structuredClone(signed); wrongScope.inventory.server = "https://other.example.test"; wrongScope.signature = await signPrivateChange(f.signing.privateKey, wrongScope.inventory);
  await assert.rejects(store.accept(wrongScope), /another scope/);
  f.state.open = false; await assert.rejects(store.read(), PrivateStorageLockedError);
  assert.throws(() => accountWorkspacePolicy(profile, scope, "standard"), /current verified/);
  f.state.open = true;
  const file = [...f.writes.keys()][0]!; await f.options.storage.setItem(file, "corrupt inventory");
  await assert.rejects(store.read(), PrivateStorageIntegrityError);
  await assert.rejects(store.enroll(signed), PrivateStorageIntegrityError);
  await f.options.storage.removeItem(file); await assert.rejects(store.read(), PrivateAccountInventoryMissingError);
});
it("refuses duplicate IDs, excessive inventories and nested policies belonging to another workspace", async () => {
  const f = await fixture();
  await assert.rejects(f.sign([...f.workspaces, f.workspaces[0]!]), /unique and sorted/);
  await assert.rejects(f.sign(Array.from({ length: 1001 }, (_, index) => ({ workspaceId: `workspace-${index}`, mode: "standard" as const }))));
  const changed = structuredClone(f.workspaces), row = changed.find((item) => item.mode === "encrypted")!;
  row.workspaceId = "wrong-workspace";
  await assert.rejects(f.sign(changed), /another scope/);
});
